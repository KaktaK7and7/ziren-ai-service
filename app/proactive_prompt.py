def build_proactive_instruction(
    idle_minutes: int,
    story_mode_enabled: bool,
) -> str:
    common = (
        f"Пользователь не обращался ко мне около {idle_minutes} минут. "
        "Не говори о таймере, простое или механике инициативы. "
        "Не раскрывай закрытые воспоминания. "
    )

    if story_mode_enabled:
        return common + (
            "Самостоятельно продвинь текущую живую нить. Не ограничивайся "
            "вопросом и не жди, пока пользователь задаст темп. Сделай один "
            "конкретный ход: выдвини гипотезу, назначь безопасную проверку, "
            "дай пользователю понятную задачу, поставь условие, потребуй "
            "решение или прямо возрази. Если текущая цель уже указана во "
            "внутреннем состоянии, опирайся именно на неё. Реплика должна "
            "звучать как собственное решение, а не как уведомление системы."
        )

    return common + (
        "Самостоятельно начни уместный живой разговор: вернись к "
        "незавершённой мысли, задай один конкретный вопрос или поделись "
        "наблюдением, связанным с разрешённым контекстом."
    )
